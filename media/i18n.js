  const MESSAGES = { pt, en };

  /** 'auto' segue o idioma do VS Code: português se começar com "pt", senão inglês. */
  function resolve(setting, uiLanguage) {
    if (setting === 'pt-BR' || setting === 'pt') return 'pt';
    if (setting === 'en') return 'en';
    return String(uiLanguage || '').toLowerCase().startsWith('pt') ? 'pt' : 'en';
  }

  function create(lang) {
    const dict = MESSAGES[lang] || en;
    const t = (key, ...args) => {
      const v = key in dict ? dict[key] : pt[key];
      if (v === undefined) return key;
      return typeof v === 'function' ? v(...args) : v;
    };
    t.lang = lang;
    t.locale = dict.locale;
    return t;
  }

  const api = { create, resolve, MESSAGES };
